import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const schemaPath = resolve(process.cwd(), "../docs/api/openapi.yaml");
const generatedPath = resolve(process.cwd(), "src/types/api.generated.ts");
const normalize = (value) => value.replaceAll("\r\n", "\n").trim();

const banner = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const expected = banner + astToString(await openapiTS(pathToFileURL(schemaPath)));
const committed = await readFile(generatedPath, "utf8");

if (normalize(expected) !== normalize(committed)) {
  console.error("Generated API types are stale. Run `npm run gen:api` and commit the result.");
  process.exitCode = 1;
}
